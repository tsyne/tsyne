export type GLConstants = typeof GL_CONSTANTS;

/** Apply all GL constants to a target object (e.g., TsyneGLProxy.prototype) */
export function applyGLConstants(target: any): void {
  for (const [key, value] of Object.entries(GL_CONSTANTS)) {
    Object.defineProperty(target, key, {
      value,
      writable: false,
      enumerable: true,
      configurable: false,
    });
  }
}
